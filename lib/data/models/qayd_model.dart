// Represents all data structures for lectures, transcripts, and summaries.
// Designed with simple toMap/fromMap serialization for easy local storage.
// ==============================================================================

/// Processing lifecycle states of a Qayd
enum QaydStatus {
  recording,
  transcribing,
  transcribed,
  summarizing,
  done,
  failed,
}

/// Spoken language detected in the audio
enum QaydLanguage {
  ar,
  en,
  mixed,
}

/// A single timestamped segment of the transcript.
/// Powers the "Tap-to-Seek" audio playback feature.
class TranscriptSegment {
  final double startSec;
  final double endSec;
  final String text;

  const TranscriptSegment({
    required this.startSec,
    required this.endSec,
    required this.text,
  });

  Map<String, dynamic> toMap() {
    return {
      'startSec': startSec,
      'endSec': endSec,
      'text': text,
    };
  }

  factory TranscriptSegment.fromMap(Map<String, dynamic> map) {
    return TranscriptSegment(
      startSec: (map['startSec'] as num).toDouble(),
      endSec: (map['endSec'] as num).toDouble(),
      text: map['text'] as String? ?? '',
    );
  }
}

/// A key technical term with its definition extracted by Gemini
class KeyTerm {
  final String term;
  final String definition;

  const KeyTerm({
    required this.term,
    required this.definition,
  });

  Map<String, dynamic> toMap() {
    return {
      'term': term,
      'definition': definition,
    };
  }

  factory KeyTerm.fromMap(Map<String, dynamic> map) {
    return KeyTerm(
      term: map['term'] as String? ?? '',
      definition: map['definition'] as String? ?? '',
    );
  }
}

/// Structured academic summary generated by Gemini Flash
class QaydSummary {
  final String overview;
  final List<String> keyPoints;
  final List<KeyTerm> keyTerms;

  const QaydSummary({
    required this.overview,
    required this.keyPoints,
    required this.keyTerms,
  });

  Map<String, dynamic> toMap() {
    return {
      'overview': overview,
      'keyPoints': keyPoints,
      'keyTerms': keyTerms.map((k) => k.toMap()).toList(),
    };
  }

  factory QaydSummary.fromMap(Map<String, dynamic> map) {
    return QaydSummary(
      overview: map['overview'] as String? ?? '',
      keyPoints: (map['keyPoints'] as List<dynamic>?)
              ?.map((e) => e.toString())
              .toList() ??
          [],
      keyTerms: (map['keyTerms'] as List<dynamic>?)
              ?.map((e) => KeyTerm.fromMap(Map<String, dynamic>.from(e as Map)))
              .toList() ??
          [],
    );
  }
}

/// The core Lecture entity representing a saved Qayd
class Qayd {
  final String id;
  final String title;
  final DateTime createdAt;
  final int durationSec;
  final String audioPath;
  final QaydLanguage language;
  final String transcript;
  final List<TranscriptSegment> segments;
  final QaydSummary? summary;
  final QaydStatus status;
  final String? folderId;

  const Qayd({
    required this.id,
    required this.title,
    required this.createdAt,
    required this.durationSec,
    required this.audioPath,
    this.language = QaydLanguage.mixed,
    this.transcript = '',
    this.segments = const [],
    this.summary,
    this.status = QaydStatus.done,
    this.folderId,
  });

  /// Creates a copy of this Qayd with updated fields (immutability helper)
  Qayd copyWith({
    String? id,
    String? title,
    DateTime? createdAt,
    int? durationSec,
    String? audioPath,
    QaydLanguage? language,
    String? transcript,
    List<TranscriptSegment>? segments,
    QaydSummary? summary,
    QaydStatus? status,
    String? folderId,
  }) {
    return Qayd(
      id: id ?? this.id,
      title: title ?? this.title,
      createdAt: createdAt ?? this.createdAt,
      durationSec: durationSec ?? this.durationSec,
      audioPath: audioPath ?? this.audioPath,
      language: language ?? this.language,
      transcript: transcript ?? this.transcript,
      segments: segments ?? this.segments,
      summary: summary ?? this.summary,
      status: status ?? this.status,
      folderId: folderId ?? this.folderId,
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'title': title,
      'createdAt': createdAt.toIso8601String(),
      'durationSec': durationSec,
      'audioPath': audioPath,
      'language': language.name,
      'transcript': transcript,
      'segments': segments.map((s) => s.toMap()).toList(),
      'summary': summary?.toMap(),
      'status': status.name,
      'folderId': folderId,
    };
  }

  factory Qayd.fromMap(Map<String, dynamic> map) {
    return Qayd(
      id: map['id'] as String,
      title: map['title'] as String? ?? 'Untitled Qayd',
      createdAt: DateTime.tryParse(map['createdAt'] as String? ?? '') ??
          DateTime.now(),
      durationSec: (map['durationSec'] as num?)?.toInt() ?? 0,
      audioPath: map['audioPath'] as String? ?? '',
      language: QaydLanguage.values.firstWhere(
        (e) => e.name == map['language'],
        orElse: () => QaydLanguage.mixed,
      ),
      transcript: map['transcript'] as String? ?? '',
      segments: (map['segments'] as List<dynamic>?)
              ?.map((e) =>
                  TranscriptSegment.fromMap(Map<String, dynamic>.from(e as Map)))
              .toList() ??
          [],
      summary: map['summary'] != null
          ? QaydSummary.fromMap(
              Map<String, dynamic>.from(map['summary'] as Map))
          : null,
      status: QaydStatus.values.firstWhere(
        (e) => e.name == map['status'],
        orElse: () => QaydStatus.done,
      ),
      folderId: map['folderId'] as String?,
    );
  }
}
